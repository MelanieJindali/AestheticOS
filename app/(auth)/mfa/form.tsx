"use client";

import { useActionState, useEffect, useState } from "react";
import { enrollMfa, verifyMfa } from "@/app/actions/auth";
import { Button, Field, Input } from "@/components/ui";

export function MfaForm({ factorId }: { factorId?: string }) {
  const [enroll, setEnroll] = useState<{ factorId: string; qr: string; secret: string } | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [state, action, pending] = useActionState(verifyMfa, null);

  useEffect(() => {
    if (factorId) return;
    enrollMfa().then((r) => (r.ok && r.data ? setEnroll(r.data as never) : setErr(r.error ?? "Error")));
  }, [factorId]);

  const id = factorId ?? enroll?.factorId;
  return (
    <form action={action} className="mt-6 flex flex-col gap-4">
      {!factorId && enroll && (
        <div className="flex flex-col items-center gap-2">
          {/* QR is an SVG data URI generated by Supabase Auth */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={enroll.qr} alt="QR code to add Aesthetic OS to your authenticator app" width={180} height={180} className="rounded-xl bg-white p-2" />
          <details className="text-xs text-muted"><summary>Can&apos;t scan? Enter this key</summary><code className="break-all select-all">{enroll.secret}</code></details>
        </div>
      )}
      {err && <p role="alert" className="text-sm text-danger">{err}</p>}
      <input type="hidden" name="factorId" value={id ?? ""} />
      <Field label="Code from your app" htmlFor="code"><Input id="code" name="code" inputMode="numeric" autoComplete="one-time-code" pattern="\d{6}" maxLength={6} required /></Field>
      {state?.error && <p role="alert" className="text-sm text-danger">{state.error}</p>}
      <Button disabled={pending || !id}>{pending ? "Verifying…" : "Verify"}</Button>
    </form>
  );
}
