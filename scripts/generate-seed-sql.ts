// Generates supabase/seed.sql: the "Luna Lash Studio" demo brand with 30 days
// of content, for local Supabase development (`supabase db reset`).
// Usage: npm run seed:sql
import { buildDemoSeed } from "../lib/seed/demo";

const DEMO_USER = "00000000-0000-0000-0000-00000000d3e0";
const d = buildDemoSeed(DEMO_USER, new Date());

const snake = (k: string) => k.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const lit = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v) && v.every((x) => typeof x === "string")) return `array[${v.map(lit).join(",")}]::text[]`;
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
// Columns stored as jsonb even when the value is an array of strings.
const JSONB = new Set(["services", "palette", "typography", "voice", "slots", "slides", "script", "compliance", "platforms", "meta", "keys"]);

function insert(table: string, rows: object[]) {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]);
  return rows.map((r) => {
    const rec = r as Record<string, unknown>;
    const vals = cols.map((c) => (JSONB.has(c) ? `'${JSON.stringify(rec[c] ?? null).replace(/'/g, "''")}'::jsonb` : lit(rec[c])));
    return `insert into public.${table} (${cols.map(snake).join(", ")}) values (${vals.join(", ")});`;
  }).join("\n") + "\n";
}

const out = [
  "-- Generated by scripts/generate-seed-sql.ts. Demo data only; all people are fictional.",
  `insert into auth.users (id, email) values ('${DEMO_USER}', 'demo@aesthetic-os.local') on conflict do nothing;`,
  insert("user_settings", [d.settings]),
  insert("brand_profiles", [d.brand]),
  insert("consent_records", d.consents),
  insert("posts", d.posts),
  insert("post_variants", d.variants),
  insert("schedule_items", d.schedule),
  insert("metric_snapshots", d.metrics),
  insert("agent_memory", d.memory),
  insert("goals", d.goals),
  insert("tasks", d.tasks),
].join("\n");
process.stdout.write(out);
